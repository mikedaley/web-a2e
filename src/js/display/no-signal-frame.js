const GLYPH_W = 5;
const GLYPH_H = 7;

// One logical Apple pixel is two framebuffer pixels across and two down, so a
// character cell here matches the 7x8 cell of the real 40-column text screen.
const PIXEL = 2;
const CELL_W = 7 * PIXEL;
const CELL_H = 8 * PIXEL;

// Composite white is never paper white. This is the level the emulator's own
// text output sits at, so the message matches what appears a moment later.
const FG = [0xe8, 0xe8, 0xe8];
const DIM = [0x8c, 0x8c, 0x8c];

/**
 * Build the powered-off screen.
 *
 * @param {number} width  framebuffer width in pixels; callers pass the
 *                         machine's, and the //e's size is the default
 * @param {number} height framebuffer height in pixels (384)
 * @param {string} machine what to switch on, as the machine's own mark writes
 *                         it — "//e", "II+", "//c", "IIgs" — since the message
 *                         must name the machine that is actually there
 * @returns {Uint8Array} RGBA pixel data, width * height * 4 bytes
 */
export function buildNoSignalFrame(width = 560, height = 384, machine = "//e") {
  const buf = new Uint8Array(width * height * 4);

  // Opaque black — the shader's vignette and bezel do the rest.
  for (let i = 3; i < buf.length; i += 4) buf[i] = 0xff;

  const plot = (x, y, rgb) => {
    if (x < 0 || y < 0 || x >= width || y >= height) return;
    const o = (y * width + x) * 4;
    buf[o] = rgb[0];
    buf[o + 1] = rgb[1];
    buf[o + 2] = rgb[2];
  };

  const fillRect = (x, y, w, h, rgb) => {
    for (let dy = 0; dy < h; dy++) {
      for (let dx = 0; dx < w; dx++) plot(x + dx, y + dy, rgb);
    }
  };

  // Draw text centred on the given framebuffer row, one character per cell.
  const drawTextCentred = (text, top, rgb, scale = 1) => {
    const cellW = CELL_W * scale;
    const runW = text.length * cellW;
    let x = Math.round((width - runW) / 2);
    for (const ch of text) {
      const glyph = FONT[ch] || FONT[" "];
      for (let row = 0; row < GLYPH_H; row++) {
        const bits = glyph[row];
        for (let col = 0; col < GLYPH_W; col++) {
          if (!(bits & (1 << (GLYPH_W - 1 - col)))) continue;
          fillRect(
            x + col * PIXEL * scale,
            top + row * PIXEL * scale,
            PIXEL * scale,
            PIXEL * scale,
            rgb,
          );
        }
      }
      x += cellW;
    }
  };

  // Vertical layout, top down: heading then message, centred on the screen.
  // Rows are snapped to whole character cells so the text sits on the same grid
  // the emulator's own text screen uses.
  //
  // There is deliberately no power symbol here. One used to sit below the text,
  // and on a canvas that ignores clicks it only invited people to press it
  // instead of the real power button in the toolbar.
  const cellRow = (row) => row * CELL_H;

  drawTextCentred("NO SIGNAL", cellRow(9), FG, 2);
  drawTextCentred(`SWITCH ON THE APPLE ${machine} TO START`, cellRow(14), DIM);

  return buf;
}
